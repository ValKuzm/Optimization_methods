"""Генерация отчётов для ЛР 1 и двух заданий со звёздочкой."""
from common import ROOT, load_json

def write(path,text):
    p=ROOT/path; p.parent.mkdir(parents=True,exist_ok=True); p.write_text(text.strip()+'\n',encoding='utf-8')

def run():
    a=load_json(ROOT/'results/lab1/results.json')
    bench=load_json(ROOT/'results/benchmark/results.json')
    write('results/lab1/REPORT.md',f'''
# Лабораторная работа 1. ЛП-модель распределения ресурсов (Портфель)

Вариант 5, группа 527, N=12, seed=10212. Требуется максимум ожидаемой
годовой доходности портфеля из 6 активов при 3 линейных рисках.

## Модель

I={{1,...,6}}. x_i — доля бюджета; r_i — годовая доходность;
m_i, v_i, l_i — рыночный балл, валютная экспозиция и неликвидность.
Бюджет 100000 ₽. Данные синтетические, хранятся в data/lab1.json.

max sum(r_i*x_i), sum(x_i)=1, x_i>=0;
sum(m_i*x_i)<=0.400, sum(v_i*x_i)<=0.350, sum(l_i*x_i)<=0.280.

Все x непрерывные. Не учитываются лоты, комиссии, корреляции и налоги.
Риск — линейный условный показатель; это не дисперсия портфеля.

## Решение и проверка

HiGHS, simplex, presolve=on, threads=1. Статус optimal.
Доли: {a['base']['x']}.
Годовая доходность {a['base']['annual_return']:.12f}, прибыль
{a['base']['profit_rub']:.6f} ₽. Все 3 риска активны. A1 и A5 имеют нулевые доли.
Независимая проверка по исходным JSON на NumPy пройдена, допуск 1e-7.
Максимальное нарушение {a['base']['verification']['max_violation']:.3e}.
Цель пересчитана; дополнительная сверка с scipy.optimize.linprog успешна.

## Сценарии

| Сценарий | Изменение | Прибыль, ₽ | Статус |
|---|---|---:|---|
| Базовый | исходные лимиты | {a['base']['profit_rub']:.6f} | optimal |
| Дефицит | рыночный лимит -20% | {a['deficit']['profit_rub']:.6f} | optimal |
| Стресс | рынок и неликвидность -40% | {a['stress']['profit_rub']:.6f} | optimal |

Все решения и ограничения проверены независимо. Тени рисков:
{a['base']['shadow_prices']}. Малые прибавки 0.0001 подтверждают прогноз.
Диапазоны сохранения текущего базиса в sensitivity.csv относятся к изменению
одной правой части при фиксированных остальных. В стрессовом режиме базис меняется.

## Вывод

Ограничения риска определяют структуру доходного портфеля. Лучшая доходность
отдельного актива не означает, что нужно вложить в него всё. Ужесточение лимитов
снижает цель и меняет состав. На практике потребовались бы реальные данные,
лоты, комиссии и более содержательная оценка риска.

Файлы: solution.csv, scenarios.csv, sensitivity.csv, dual.csv,
results.json, scenario_data.json, logs/*.log, ../figures/lab1_*.png.
''')
    write('results/lab1/STAR_DUAL.md',f'''
# Задание со звёздочкой 1. Двойственная интерпретация

Прямая полная модель: max r^T x, Ax<=b, 1^T x=1, x>=0.
Двойственная: min b^T y+z, A^T y+z*1>=r, y>=0, z свободна.
Матрица A содержит все три риска и все шесть активов.

Для любых допустимых x, y, z имеем r^T x <= y^T Ax+z <= y^T b+z.
Равенство прямой и двойственной целей доказывает оптимальность в рамках
численных допусков. Получено y={a['dual']['x'][:3]}, z={a['dual']['x'][3]}.
Обе цели равны {a['base']['annual_return']:.12f}.
Численный разрыв {a['dual']['verification']['duality_gap']:.3e}.

Проверены: знаки y, все 6 двойственных неравенств, обе допустимости,
равенство целей и дополняющая нежёсткость:
y_j*(b_j-(Ax)_j)=0 и x_i*((A^T y+z*1)_i-r_i)=0.
Положительные y означают предельную ценность разрешения дополнительного риска.
Для прибавки лимита 0.01 годовая прибыль при бюджете 100000 меняется примерно
на 1000*y рублей. Это локальный эффект, а не гарантированный реальный доход.
z относится к RHS нормировки суммы долей и не является прямой ценой рубля.

У A1/A5 положительные двойственные запасы, их оптимальные доли нулевые.
Четыре купленных актива имеют нулевой запас. Подробные значения: dual.csv,
results.json. Лог отдельного решения: logs/dual.log.
''')
    lines=['| n | m | simplex median, с | IPX median, с |','|---:|---:|---:|---:|']
    for task in range(1,11):
        s=next(v for v in bench['rows'] if v['task']==task and v['method']=='simplex')
        i=next(v for v in bench['rows'] if v['task']==task and v['method']=='ipx')
        lines.append(f"| {s['variables']} | {s['risk_constraints']} | {s['median_time_s']:.7f} | {i['median_time_s']:.7f} |")
    write('results/benchmark/STAR_BENCHMARK.md','''
# Задание со звёздочкой 2. Сравнение методов (Симплекс vs IPX)

10 LP растущего размера: max r*x, sum(x)=1, Ax<=b, x>=0.
Все данные генерируются явно описанным алгоритмом в src/benchmark.py,
seeds 11212...11221. Сначала создаётся допустимый w, затем b=Aw+положительный запас.
Сравниваются simplex и явный IPX; presolve on, threads 1, crossover on.
По одному прогреву ветви, затем 5 новых решателей на каждую пару задача/метод.
Время охватывает h.run(), но не генерацию и сборку матрицы. Политика логирования одинакова.

'''+ '\n'.join(lines)+'''

Все 100 решений проверены по исходным ограничениям на NumPy с допуском 1e-7.
Цели методов совпали. В summary.csv — медиана, min/max и итерации; в runs.csv —
все отдельные замеры. Сохранены 100 логов и график ../figures/benchmark.png.
На этом семействе симплекс быстрее, но это не универсальный вывод.
Итерации разных алгоритмов имеют разную стоимость, а времена зависят от машины.
''')

if __name__=='__main__': run()